-- Esquema do banco comercial (contas, sessões, licenças, pagamentos e auditoria).
-- Compatível com PostgreSQL (produção) e H2 (testes e desenvolvimento).
-- Este banco NUNCA recebe dados da exportação do Instagram.

CREATE TABLE conta (
    id UUID PRIMARY KEY,
    email VARCHAR(254) NOT NULL,
    email_normalizado VARCHAR(254) NOT NULL,
    nome VARCHAR(100) NOT NULL,
    hash_senha VARCHAR(255) NOT NULL,
    papel VARCHAR(20) NOT NULL,
    email_verificado BOOLEAN NOT NULL,
    ativa BOOLEAN NOT NULL,
    tentativas_falhas INT NOT NULL,
    bloqueada_ate TIMESTAMP,
    criada_em TIMESTAMP NOT NULL,
    atualizada_em TIMESTAMP NOT NULL,
    CONSTRAINT uq_conta_email UNIQUE (email_normalizado),
    CONSTRAINT ck_conta_papel CHECK (papel IN ('CLIENTE', 'MASTER'))
);

CREATE TABLE sessao (
    id UUID PRIMARY KEY,
    conta_id UUID NOT NULL REFERENCES conta (id),
    hash_token VARCHAR(64) NOT NULL,
    dispositivo_id VARCHAR(64) NOT NULL,
    nome_dispositivo VARCHAR(100),
    criada_em TIMESTAMP NOT NULL,
    ultimo_uso TIMESTAMP NOT NULL,
    expira_em TIMESTAMP NOT NULL,
    revogada_em TIMESTAMP,
    CONSTRAINT uq_sessao_token UNIQUE (hash_token)
);
CREATE INDEX idx_sessao_conta ON sessao (conta_id);

CREATE TABLE token_uso_unico (
    id UUID PRIMARY KEY,
    conta_id UUID NOT NULL REFERENCES conta (id),
    finalidade VARCHAR(30) NOT NULL,
    hash_token VARCHAR(64) NOT NULL,
    criado_em TIMESTAMP NOT NULL,
    expira_em TIMESTAMP NOT NULL,
    usado_em TIMESTAMP,
    CONSTRAINT uq_token_hash UNIQUE (hash_token),
    CONSTRAINT ck_token_finalidade CHECK (finalidade IN ('VERIFICACAO_EMAIL', 'RECUPERACAO_SENHA'))
);

CREATE TABLE dispositivo (
    id UUID PRIMARY KEY,
    conta_id UUID NOT NULL REFERENCES conta (id),
    identificador VARCHAR(64) NOT NULL,
    nome VARCHAR(100),
    ativado_em TIMESTAMP NOT NULL,
    revogado_em TIMESTAMP,
    CONSTRAINT uq_dispositivo UNIQUE (conta_id, identificador)
);

CREATE TABLE plano (
    id VARCHAR(40) PRIMARY KEY,
    nome VARCHAR(100) NOT NULL,
    descricao VARCHAR(300) NOT NULL,
    periodicidade VARCHAR(20) NOT NULL,
    preco_centavos BIGINT NOT NULL,
    moeda VARCHAR(3) NOT NULL,
    ativo BOOLEAN NOT NULL,
    CONSTRAINT ck_plano_periodicidade CHECK (periodicidade IN ('MENSAL', 'ANUAL')),
    CONSTRAINT ck_plano_preco CHECK (preco_centavos >= 0)
);

CREATE TABLE pedido (
    id UUID PRIMARY KEY,
    conta_id UUID NOT NULL REFERENCES conta (id),
    plano_id VARCHAR(40) NOT NULL REFERENCES plano (id),
    valor_centavos BIGINT NOT NULL,
    moeda VARCHAR(3) NOT NULL,
    situacao VARCHAR(30) NOT NULL,
    referencia_provedor VARCHAR(200),
    sandbox BOOLEAN NOT NULL,
    criado_em TIMESTAMP NOT NULL,
    atualizado_em TIMESTAMP NOT NULL
);
CREATE INDEX idx_pedido_conta ON pedido (conta_id);

CREATE TABLE assinatura (
    id UUID PRIMARY KEY,
    conta_id UUID NOT NULL REFERENCES conta (id),
    plano_id VARCHAR(40) NOT NULL REFERENCES plano (id),
    situacao VARCHAR(30) NOT NULL,
    periodo_fim TIMESTAMP,
    ultimo_evento_em TIMESTAMP,
    criada_em TIMESTAMP NOT NULL,
    atualizada_em TIMESTAMP NOT NULL,
    CONSTRAINT uq_assinatura_conta UNIQUE (conta_id)
);

CREATE TABLE concessao (
    id UUID PRIMARY KEY,
    conta_id UUID NOT NULL REFERENCES conta (id),
    origem VARCHAR(40) NOT NULL,
    inicio TIMESTAMP NOT NULL,
    fim TIMESTAMP,
    concedida_por UUID,
    motivo VARCHAR(200) NOT NULL,
    revogada_em TIMESTAMP
);
CREATE INDEX idx_concessao_conta ON concessao (conta_id);

CREATE TABLE licenca_emitida (
    id UUID PRIMARY KEY,
    conta_id UUID NOT NULL REFERENCES conta (id),
    dispositivo_id UUID NOT NULL REFERENCES dispositivo (id),
    emitida_em TIMESTAMP NOT NULL,
    valida_ate TIMESTAMP NOT NULL,
    tolerancia_ate TIMESTAMP NOT NULL,
    origem VARCHAR(40) NOT NULL,
    revogada_em TIMESTAMP
);
CREATE INDEX idx_licenca_conta ON licenca_emitida (conta_id);

CREATE TABLE evento_pagamento (
    id VARCHAR(100) PRIMARY KEY,
    tipo VARCHAR(40) NOT NULL,
    recebido_em TIMESTAMP NOT NULL,
    criado_no_provedor_em TIMESTAMP NOT NULL,
    pedido_id UUID,
    resultado VARCHAR(40) NOT NULL
);

CREATE TABLE auditoria (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ocorrido_em TIMESTAMP NOT NULL,
    ator_id UUID,
    ator_tipo VARCHAR(20) NOT NULL,
    acao VARCHAR(60) NOT NULL,
    alvo VARCHAR(100),
    detalhe VARCHAR(300)
);
CREATE INDEX idx_auditoria_ocorrido ON auditoria (ocorrido_em);
